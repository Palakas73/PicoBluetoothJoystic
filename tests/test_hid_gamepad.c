#include "controllers/hid_gamepad.h"
#include <stdio.h>
#include <string.h>
static int fails;
static void check(int ok, const char *name) {
  printf("%s %s\n", ok ? "PASS" : "FAIL", name);
  if (!ok)
    fails++;
}
/* Xbox Wireless Controller 045e:0b13 BLE Report Map, community capture; see
   docs/research.md. The parser computes field positions from this descriptor;
   offsets are not hard-coded. */
static const uint8_t map[] = {
    0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01, 0x09, 0x01, 0xa1, 0x00,
    0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x27, 0xff, 0xff, 0x00, 0x00, 0x95,
    0x02, 0x75, 0x10, 0x81, 0x02, 0xc0, 0x09, 0x01, 0xa1, 0x00, 0x09, 0x32,
    0x09, 0x35, 0x15, 0x00, 0x27, 0xff, 0xff, 0x00, 0x00, 0x95, 0x02, 0x75,
    0x10, 0x81, 0x02, 0xc0, 0x05, 0x02, 0x09, 0xc5, 0x15, 0x00, 0x26, 0xff,
    0x03, 0x95, 0x01, 0x75, 0x0a, 0x81, 0x02, 0x15, 0x00, 0x25, 0x00, 0x75,
    0x06, 0x95, 0x01, 0x81, 0x03, 0x05, 0x02, 0x09, 0xc4, 0x15, 0x00, 0x26,
    0xff, 0x03, 0x95, 0x01, 0x75, 0x0a, 0x81, 0x02, 0x15, 0x00, 0x25, 0x00,
    0x75, 0x06, 0x95, 0x01, 0x81, 0x03, 0x05, 0x01, 0x09, 0x39, 0x15, 0x01,
    0x25, 0x08, 0x35, 0x00, 0x46, 0x3b, 0x01, 0x66, 0x14, 0x00, 0x75, 0x04,
    0x95, 0x01, 0x81, 0x42, 0x75, 0x04, 0x95, 0x01, 0x15, 0x00, 0x25, 0x00,
    0x35, 0x00, 0x45, 0x00, 0x65, 0x00, 0x81, 0x03, 0x05, 0x09, 0x19, 0x01,
    0x29, 0x0f, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0f, 0x81, 0x02,
    0x15, 0x00, 0x25, 0x00, 0x75, 0x01, 0x95, 0x01, 0x81, 0x03, 0x05, 0x0c,
    0x0a, 0xb2, 0x00, 0x15, 0x00, 0x25, 0x01, 0x95, 0x01, 0x75, 0x01, 0x81,
    0x02, 0x15, 0x00, 0x25, 0x00, 0x75, 0x07, 0x95, 0x01, 0x81, 0x03};
int main(void) {
  hid_gamepad_parser_t p;
  controller_state_t s;
  uint8_t sample[17] = {0x01, 0x00, 0x40, 0xff, 0xff, 0x00, 0x00, 0x40, 0x00,
                        0xff, 0x03, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00};
  sample[14] = 0xdb;
  sample[15] = 0x7c;
  sample[16] = 1;
  check(hid_gamepad_parser_reset(&p, map, sizeof(map)),
        "parse captured Xbox HID Report Map");
  check(p.input_bits[1] == 128, "derive 128-bit payload size from the map");
  check(hid_gamepad_parser_decode(&p, 1, sample, sizeof(sample), &s),
        "decode report according to Report Map");
  check(s.left_x == -16384 && s.left_y == 32767 && s.right_x == -32768 &&
            s.right_y == -32704,
        "normalize full-range axes using descriptor logical bounds");
  check(s.left_trigger == 65535 && s.right_trigger == 0,
        "normalize 10-bit trigger range without losing input steps");
  check(s.dpad == 0, "extract hat field");
  check(s.buttons == (CTRL_A | CTRL_B | CTRL_X | CTRL_Y | CTRL_LB | CTRL_RB |
                      CTRL_VIEW | CTRL_MENU | CTRL_GUIDE | CTRL_L3 | CTRL_R3) &&
            s.share == 1,
        "map all Xbox button usages and Share");
  check(!hid_gamepad_parser_decode(&p, 1, sample, 2, &s),
        "reject truncated report");
  sample[14] = 0;
  sample[15] = 0;
  sample[16] = 0;
  check(hid_gamepad_parser_decode(&p, 1, sample, sizeof(sample), &s) &&
            s.buttons == 0 && s.share == 0,
        "clear digital controls when released");
  controller_state_neutral(&s);
  check(s.buttons == 0 && s.dpad == 8 && s.left_x == 0 && s.left_y == 0 &&
            s.right_x == 0 && s.right_y == 0 && s.left_trigger == 0 &&
            s.right_trigger == 0,
        "neutral state");
  return fails ? 1 : 0;
}
